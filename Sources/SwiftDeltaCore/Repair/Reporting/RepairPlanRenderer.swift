import Foundation

public enum RepairPlanOutputFormat: String, Codable, CaseIterable, Sendable {
    case diff
    case json
}

public enum RepairPlanRenderer {
    public static func render(
        _ plan: RepairPlan,
        format: RepairPlanOutputFormat
    ) throws -> Data {
        switch format {
        case .json:
            try RepairPlanJSON.encode(plan)
        case .diff:
            Data(try terminalDiff(plan).utf8)
        }
    }

    public static func write(_ data: Data, to output: URL) throws {
        do {
            let parent = output.deletingLastPathComponent()
            try FileManager.default.createDirectory(
                at: parent,
                withIntermediateDirectories: true
            )
            try data.write(to: output, options: [.atomic])
        } catch {
            throw SwiftDeltaError.outputWrite(
                path: output.path,
                reason: error.localizedDescription
            )
        }
    }

    private static func terminalDiff(_ plan: RepairPlan) throws -> String {
        var header = [
            "Repair plan \(plan.repairPlanFormatVersion)",
            "Project: \(plan.projectRoot)",
            "Repairs: \(plan.repairs.count) "
                + "(safe: \(plan.repairs.count { $0.safety == .safe }))",
        ]
        let generatedCount = plan.repairs.count { $0.modelGenerated == true }
        if generatedCount > 0 {
            header.append("Foundation Models: \(generatedCount)")
        }
        header.append("Conflicts: \(plan.conflicts.count)")
        header.append("")
        var output = header.joined(separator: "\n")
        for repair in plan.repairs where repair.safety != .safe {
            output += "[\(repair.safety.rawValue)] \(repair.repairIdentifier) "
                + "\(repair.filePath):\(repair.sourceRange.start.line):"
                + "\(repair.sourceRange.start.column)\n"
        }
        for conflict in plan.conflicts {
            output += "[conflict:\(conflict.kind.rawValue)] "
                + "\(conflict.repairIdentifiers.joined(separator: ", "))\n"
        }
        if !plan.conflicts.isEmpty || plan.repairs.contains(where: { $0.safety != .safe }) {
            output += "\n"
        }
        for repair in plan.repairs where repair.modelGenerated == true {
            output += """
            Repair source: \(repair.generatedBy ?? "Apple Foundation Models")
            Execution: \(repair.execution ?? "unknown")
            Host model generation: \(repair.hostModelGeneration ?? "unknown")
            Reasoning level: \(repair.reasoningLevel ?? "unsupported")
            Review required: yes
            Generated by Apple Foundation Models. Review and build verification are required.

            """
        }
        for failure in plan.planningFailures
            where failure.message.contains("Foundation Models")
        {
            output += "\(foundationModelsFailureLabel(failure.message)): "
                + "\(failure.message)\n"
        }
        if plan.planningFailures.contains(where: {
            $0.message.contains("Foundation Models")
        }) {
            output += "\n"
        }
        let conflictIdentifiers = Set(plan.conflicts.flatMap(\.repairIdentifiers))
        let previewable = plan.repairs.filter {
            ($0.safety == .safe || $0.modelGenerated == true)
                && !conflictIdentifiers.contains($0.repairIdentifier)
        }
        guard !previewable.isEmpty else {
            throw RepairError.invalidPlan(
                "the plan has no conflict-free source edits to render as a diff"
            )
        }
        output += try UnifiedRepairDiff.render(
            repairs: previewable,
            projectRoot: URL(fileURLWithPath: plan.projectRoot, isDirectory: true)
        )
        return output.hasSuffix("\n") ? output : output + "\n"
    }

    private static func foundationModelsFailureLabel(
        _ message: String
    ) -> String {
        let normalized = message.lowercased()
        if normalized.contains("unavailable")
            || normalized.contains("not ready")
            || normalized.contains("requires macos")
            || normalized.contains("not eligible")
            || normalized.contains("disabled")
        {
            return "Foundation Models unavailable"
        }
        if normalized.contains("timed out") {
            return "Foundation Models timed out"
        }
        if normalized.contains("anchor") || normalized.contains("ambiguous") {
            return "Foundation Models source anchor rejected"
        }
        if normalized.contains("verification") {
            return "Foundation Models verification failed"
        }
        if normalized.contains("structured") || normalized.contains("generation") {
            return "Foundation Models generation failed"
        }
        return "Foundation Models proposal rejected"
    }
}

enum UnifiedRepairDiff {
    static func render(
        repairs: [ProposedRepair],
        projectRoot: URL
    ) throws -> String {
        let grouped = Dictionary(grouping: repairs, by: \.filePath)
        var output = ""
        for path in grouped.keys.sorted() {
            let document = try RepairSourceDocument(
                root: projectRoot,
                file: projectRoot.appendingPathComponent(path)
            )
            let fileRepairs = grouped[path] ?? []
            for repair in fileRepairs {
                guard repair.fileFingerprint == document.fingerprint,
                      try document.text(in: repair.sourceRange) == repair.originalText
                else {
                    throw RepairError.stalePlan(path)
                }
            }
            var changed = document.data
            for repair in fileRepairs.sorted(by: {
                $0.sourceRange.start.utf8Offset > $1.sourceRange.start.utf8Offset
            }) {
                let byteRange = repair.sourceRange.start.utf8Offset..<repair.sourceRange.end.utf8Offset
                changed.replaceSubrange(
                    byteRange,
                    with: Data(repair.replacementText.utf8)
                )
            }
            output += diff(
                original: document.data,
                changed: changed,
                path: path
            )
        }
        return output
    }

    private static func diff(original: Data, changed: Data, path: String) -> String {
        guard original != changed else {
            return ""
        }
        let oldLines = lines(original)
        let newLines = lines(changed)
        var prefix = 0
        while prefix < oldLines.count,
              prefix < newLines.count,
              oldLines[prefix] == newLines[prefix]
        {
            prefix += 1
        }
        var suffix = 0
        while suffix < oldLines.count - prefix,
              suffix < newLines.count - prefix,
              oldLines[oldLines.count - suffix - 1]
                == newLines[newLines.count - suffix - 1]
        {
            suffix += 1
        }
        let context = 3
        let oldLower = max(0, prefix - context)
        let newLower = max(0, prefix - context)
        let oldUpper = min(oldLines.count, oldLines.count - suffix + context)
        let newUpper = min(newLines.count, newLines.count - suffix + context)
        let oldChangedLower = prefix
        let oldChangedUpper = oldLines.count - suffix
        let newChangedLower = prefix
        let newChangedUpper = newLines.count - suffix
        var result = "--- a/\(path)\n+++ b/\(path)\n"
        result += "@@ -\(oldLower + 1),\(oldUpper - oldLower) "
            + "+\(newLower + 1),\(newUpper - newLower) @@\n"
        for index in oldLower..<oldChangedLower {
            result += " \(oldLines[index])\n"
        }
        for index in oldChangedLower..<oldChangedUpper {
            result += "-\(oldLines[index])\n"
        }
        for index in newChangedLower..<newChangedUpper {
            result += "+\(newLines[index])\n"
        }
        for offset in 0..<min(
            oldUpper - oldChangedUpper,
            newUpper - newChangedUpper
        ) {
            result += " \(oldLines[oldChangedUpper + offset])\n"
        }
        return result
    }

    private static func lines(_ data: Data) -> [String] {
        String(decoding: data, as: UTF8.self)
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map(String.init)
    }
}
